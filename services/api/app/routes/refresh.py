"""Refresh engine API routes: proposals, approval flow, and manual scan trigger.

Provides CRUD and lifecycle operations for refresh proposals generated by the
decay detection scanner, plus an endpoint to manually trigger a scan.
"""

from __future__ import annotations

from typing import Annotated, Any
from uuid import UUID

from fastapi import APIRouter, BackgroundTasks, Depends, HTTPException, Query, status
from pydantic import BaseModel, Field
from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession

from services.api.app.auth import (
    AuthUser,
    MemberRole,
    has_client_access,
    require_roles,
)
from services.api.app.db import get_db
from services.api.app.logging import get_logger
from services.workers.app.refresh_scanner import (
    approve_refresh_and_republish,
    scan_client_content,
)

logger = get_logger(__name__)

router = APIRouter(prefix="/clients/{client_id}/refresh", tags=["refresh"])

OPS_ROLES = (
    MemberRole.STRATEGIST,
    MemberRole.EDITOR,
    MemberRole.ADMIN,
    MemberRole.OWNER,
)


# ───────────── Schemas ─────────────

class RefreshProposalResponse(BaseModel):
    id: UUID
    content_item_id: UUID
    client_id: UUID
    reason: dict[str, Any] | None = None
    diff_summary: str | None = None
    proposed_version_id: UUID | None = None
    reviewer_id: UUID | None = None
    status: str
    decided_at: str | None = None
    created_at: str | None = None
    # Content item details
    item_title: str | None = None
    item_slug: str | None = None
    item_published_url: str | None = None
    decay_score: float | None = None


class RefreshDecisionRequest(BaseModel):
    action: str = Field(..., description="approve | reject | defer")


class ScanResultResponse(BaseModel):
    scanned: int = 0
    flagged: int = 0
    proposals_created: int = 0


# ───────────── Routes ─────────────

@router.get("/proposals", response_model=list[RefreshProposalResponse])
async def list_refresh_proposals(
    client_id: UUID,
    proposal_status: str = Query("pending", alias="status"),
    limit: int = Query(50, ge=1, le=200),
    user: AuthUser = Depends(require_roles(*OPS_ROLES)),
    db: AsyncSession = Depends(get_db),
) -> list[RefreshProposalResponse]:
    """List refresh proposals for a client, optionally filtered by status."""
    await has_client_access(client_id, user, db)

    result = await db.execute(
        text("""
            SELECT
                rp.id, rp.content_item_id, rp.client_id,
                rp.reason, rp.diff_summary, rp.proposed_version_id,
                rp.reviewer_id, rp.status, CAST(rp.decided_at AS text),
                CAST(rp.created_at AS text),
                cv.title AS item_title,
                ci.slug AS item_slug,
                ci.published_url AS item_published_url,
                ci.decay_score
            FROM refresh_proposals rp
            JOIN content_items ci ON ci.id = rp.content_item_id
            LEFT JOIN content_versions cv ON cv.id = ci.current_version_id
            WHERE rp.client_id = :cid
              AND rp.status = :status
            ORDER BY ci.decay_score DESC NULLS LAST, rp.created_at DESC
            LIMIT :limit
        """),
        {"cid": str(client_id), "status": proposal_status, "limit": limit},
    )
    rows = result.all()

    return [
        RefreshProposalResponse(
            id=r[0], content_item_id=r[1], client_id=r[2],
            reason=r[3] if isinstance(r[3], dict) else None,
            diff_summary=r[4], proposed_version_id=r[5],
            reviewer_id=r[6], status=r[7],
            decided_at=r[8], created_at=r[9],
            item_title=r[10], item_slug=r[11],
            item_published_url=r[12],
            decay_score=float(r[13]) if r[13] is not None else None,
        )
        for r in rows
    ]


@router.get("/proposals/{proposal_id}", response_model=RefreshProposalResponse)
async def get_refresh_proposal(
    client_id: UUID,
    proposal_id: UUID,
    user: AuthUser = Depends(require_roles(*OPS_ROLES)),
    db: AsyncSession = Depends(get_db),
) -> RefreshProposalResponse:
    """Get a single refresh proposal with details."""
    await has_client_access(client_id, user, db)

    result = await db.execute(
        text("""
            SELECT
                rp.id, rp.content_item_id, rp.client_id,
                rp.reason, rp.diff_summary, rp.proposed_version_id,
                rp.reviewer_id, rp.status, CAST(rp.decided_at AS text),
                CAST(rp.created_at AS text),
                cv.title AS item_title,
                ci.slug AS item_slug,
                ci.published_url AS item_published_url,
                ci.decay_score
            FROM refresh_proposals rp
            JOIN content_items ci ON ci.id = rp.content_item_id
            LEFT JOIN content_versions cv ON cv.id = ci.current_version_id
            WHERE rp.id = :pid AND rp.client_id = :cid
        """),
        {"pid": str(proposal_id), "cid": str(client_id)},
    )
    r = result.one_or_none()
    if not r:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Refresh proposal not found")

    return RefreshProposalResponse(
        id=r[0], content_item_id=r[1], client_id=r[2],
        reason=r[3] if isinstance(r[3], dict) else None,
        diff_summary=r[4], proposed_version_id=r[5],
        reviewer_id=r[6], status=r[7],
        decided_at=r[8], created_at=r[9],
        item_title=r[10], item_slug=r[11],
        item_published_url=r[12],
        decay_score=float(r[13]) if r[13] is not None else None,
    )


@router.post("/proposals/{proposal_id}/decide")
async def decide_refresh_proposal(
    client_id: UUID,
    proposal_id: UUID,
    body: RefreshDecisionRequest,
    background: BackgroundTasks,
    user: AuthUser = Depends(require_roles(*OPS_ROLES)),
    db: AsyncSession = Depends(get_db),
) -> dict[str, Any]:
    """Approve, reject, or defer a refresh proposal."""
    await has_client_access(client_id, user, db)

    if body.action not in ("approve", "reject", "defer"):
        raise HTTPException(status.HTTP_400_BAD_REQUEST, "Action must be approve, reject, or defer")

    if body.action == "approve":
        result = await approve_refresh_and_republish(
            proposal_id=proposal_id,
            client_id=client_id,
            reviewer_id=user.user_id,
        )
        if "error" in result:
            raise HTTPException(status.HTTP_404_NOT_FOUND, result["error"])
        return {"status": "approved", **result}

    # reject or defer
    new_status = "rejected" if body.action == "reject" else "deferred"
    await db.execute(
        text("""
            UPDATE refresh_proposals
            SET status = :status,
                reviewer_id = :reviewer,
                decided_at = now()
            WHERE id = :pid AND client_id = :cid
        """),
        {
            "status": new_status,
            "pid": str(proposal_id),
            "cid": str(client_id),
            "reviewer": str(user.user_id),
        },
    )
    # Also update the corresponding approval
    await db.execute(
        text("""
            UPDATE approvals
            SET status = :status,
                reviewer_id = :reviewer,
                decided_at = now()
            WHERE subject_type = 'refresh'
              AND subject_id = :pid
              AND client_id = :cid
        """),
        {
            "status": "rejected" if body.action == "reject" else "pending",
            "pid": str(proposal_id),
            "cid": str(client_id),
            "reviewer": str(user.user_id),
        },
    )
    await db.commit()

    return {"status": new_status, "proposal_id": str(proposal_id)}


@router.post("/scan", response_model=ScanResultResponse)
async def trigger_refresh_scan(
    client_id: UUID,
    background: BackgroundTasks,
    user: AuthUser = Depends(require_roles(*OPS_ROLES)),
    db: AsyncSession = Depends(get_db),
) -> ScanResultResponse:
    """Manually trigger a refresh scan for a client's published content."""
    await has_client_access(client_id, user, db)

    stats = await scan_client_content(client_id)
    return ScanResultResponse(**stats)
