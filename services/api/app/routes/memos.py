"""Memos API routes: listing, detail, generate, approve, finalize, and export.

Provides full lifecycle management for executive client memos generated by the
memo_generator worker, including review/approval workflow.
"""

from __future__ import annotations

from typing import Annotated, Any
from uuid import UUID

from fastapi import APIRouter, Depends, HTTPException, Query, status
from fastapi.responses import PlainTextResponse
from pydantic import BaseModel, Field
from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession

from services.api.app.auth import (
    AuthUser,
    MemberRole,
    has_client_access,
    require_roles,
)
from services.api.app.db import get_db
from services.api.app.logging import get_logger
from services.workers.app.memo_generator import generate_client_memo

logger = get_logger(__name__)

router = APIRouter(prefix="/clients/{client_id}/memos", tags=["memos"])

OPS_ROLES = (
    MemberRole.STRATEGIST,
    MemberRole.EDITOR,
    MemberRole.ADMIN,
    MemberRole.OWNER,
)


# ───────────── Schemas ─────────────

class MemoResponse(BaseModel):
    id: UUID
    client_id: UUID
    title: str | None = None
    period_start: str | None = None
    period_end: str | None = None
    metrics: dict[str, Any] | None = None
    draft_md: str | None = None
    final_md: str | None = None
    status: str
    reviewer_id: UUID | None = None
    published_at: str | None = None
    created_at: str | None = None


class MemoGenerateRequest(BaseModel):
    period_days: int = Field(30, ge=7, le=90, description="Look-back period in days")


class MemoDecisionRequest(BaseModel):
    action: str = Field(..., description="approve | reject | revise")
    comment: str | None = None
    revised_md: str | None = None


# ───────────── Routes ─────────────

@router.get("", response_model=list[MemoResponse])
async def list_memos(
    client_id: UUID,
    memo_status: str | None = Query(None, alias="status"),
    limit: int = Query(20, ge=1, le=100),
    user: AuthUser = Depends(require_roles(*OPS_ROLES)),
    db: AsyncSession = Depends(get_db),
) -> list[MemoResponse]:
    """List memos for a client, newest first."""
    await has_client_access(client_id, user, db)

    conditions = ["m.client_id = :cid"]
    params: dict[str, Any] = {"cid": str(client_id), "limit": limit}
    if memo_status:
        conditions.append("m.status = :status")
        params["status"] = memo_status

    where = " AND ".join(conditions)
    result = await db.execute(
        text(f"""
            SELECT
                m.id, m.client_id, m.title, m.period_start::text,
                m.period_end::text, m.metrics, m.draft_md, m.final_md,
                m.status, m.reviewer_id, m.published_at::text, m.created_at::text
            FROM memos m
            WHERE {where}
            ORDER BY m.period_end DESC NULLS LAST, m.created_at DESC
            LIMIT :limit
        """),
        params,
    )
    rows = result.all()

    return [
        MemoResponse(
            id=r[0], client_id=r[1], title=r[2], period_start=r[3],
            period_end=r[4], metrics=r[5] if isinstance(r[5], dict) else None,
            draft_md=r[6], final_md=r[7], status=r[8],
            reviewer_id=r[9], published_at=r[10], created_at=r[11],
        )
        for r in rows
    ]


@router.get("/{memo_id}", response_model=MemoResponse)
async def get_memo(
    client_id: UUID,
    memo_id: UUID,
    user: AuthUser = Depends(require_roles(*OPS_ROLES)),
    db: AsyncSession = Depends(get_db),
) -> MemoResponse:
    """Get a single memo with full content."""
    await has_client_access(client_id, user, db)

    result = await db.execute(
        text("""
            SELECT
                m.id, m.client_id, m.title, m.period_start::text,
                m.period_end::text, m.metrics, m.draft_md, m.final_md,
                m.status, m.reviewer_id, m.published_at::text, m.created_at::text
            FROM memos m
            WHERE m.id = :mid AND m.client_id = :cid
        """),
        {"mid": str(memo_id), "cid": str(client_id)},
    )
    r = result.one_or_none()
    if not r:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Memo not found")

    return MemoResponse(
        id=r[0], client_id=r[1], title=r[2], period_start=r[3],
        period_end=r[4], metrics=r[5] if isinstance(r[5], dict) else None,
        draft_md=r[6], final_md=r[7], status=r[8],
        reviewer_id=r[9], published_at=r[10], created_at=r[11],
    )


@router.post("/generate", status_code=status.HTTP_201_CREATED)
async def trigger_memo_generation(
    client_id: UUID,
    body: MemoGenerateRequest | None = None,
    user: AuthUser = Depends(require_roles(*OPS_ROLES)),
    db: AsyncSession = Depends(get_db),
) -> dict[str, Any]:
    """Trigger generation of a new executive memo for a client."""
    await has_client_access(client_id, user, db)

    period_days = body.period_days if body else 30
    result = await generate_client_memo(client_id, period_days=period_days)
    return result


@router.post("/{memo_id}/decide")
async def decide_memo(
    client_id: UUID,
    memo_id: UUID,
    body: MemoDecisionRequest,
    user: AuthUser = Depends(require_roles(*OPS_ROLES)),
    db: AsyncSession = Depends(get_db),
) -> dict[str, Any]:
    """Approve, reject, or revise a memo."""
    await has_client_access(client_id, user, db)

    if body.action not in ("approve", "reject", "revise"):
        raise HTTPException(status.HTTP_400_BAD_REQUEST, "Action must be approve, reject, or revise")

    # Get current memo
    memo_check = await db.execute(
        text("SELECT status, draft_md FROM memos WHERE id = :mid AND client_id = :cid"),
        {"mid": str(memo_id), "cid": str(client_id)},
    )
    memo = memo_check.one_or_none()
    if not memo:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Memo not found")

    if body.action == "approve":
        final_md = memo[1]  # Use draft as final unless revised
        await db.execute(
            text("""
                UPDATE memos
                SET status = 'approved',
                    final_md = COALESCE(final_md, draft_md),
                    reviewer_id = :reviewer
                WHERE id = :mid AND client_id = :cid
            """),
            {"mid": str(memo_id), "cid": str(client_id), "reviewer": str(user.id)},
        )
        # Update approval record
        await db.execute(
            text("""
                UPDATE approvals
                SET status = 'approved', reviewer_id = :reviewer, decided_at = now(),
                    comment = :comment
                WHERE subject_type = 'memo' AND subject_id = :mid AND client_id = :cid
            """),
            {
                "mid": str(memo_id),
                "cid": str(client_id),
                "reviewer": str(user.id),
                "comment": body.comment,
            },
        )
    elif body.action == "reject":
        await db.execute(
            text("""
                UPDATE memos
                SET status = 'rejected', reviewer_id = :reviewer
                WHERE id = :mid AND client_id = :cid
            """),
            {"mid": str(memo_id), "cid": str(client_id), "reviewer": str(user.id)},
        )
        await db.execute(
            text("""
                UPDATE approvals
                SET status = 'rejected', reviewer_id = :reviewer, decided_at = now(),
                    comment = :comment
                WHERE subject_type = 'memo' AND subject_id = :mid AND client_id = :cid
            """),
            {
                "mid": str(memo_id),
                "cid": str(client_id),
                "reviewer": str(user.id),
                "comment": body.comment,
            },
        )
    else:  # revise
        if not body.revised_md:
            raise HTTPException(status.HTTP_400_BAD_REQUEST, "revised_md required for revise action")
        await db.execute(
            text("""
                UPDATE memos
                SET final_md = :revised_md, status = 'draft', reviewer_id = :reviewer
                WHERE id = :mid AND client_id = :cid
            """),
            {
                "mid": str(memo_id),
                "cid": str(client_id),
                "reviewer": str(user.id),
                "revised_md": body.revised_md,
            },
        )

    await db.commit()
    return {"status": body.action + "d", "memo_id": str(memo_id)}


@router.post("/{memo_id}/publish")
async def publish_memo(
    client_id: UUID,
    memo_id: UUID,
    user: AuthUser = Depends(require_roles(*OPS_ROLES)),
    db: AsyncSession = Depends(get_db),
) -> dict[str, Any]:
    """Publish an approved memo (make it visible in the client portal)."""
    await has_client_access(client_id, user, db)

    result = await db.execute(
        text("SELECT status FROM memos WHERE id = :mid AND client_id = :cid"),
        {"mid": str(memo_id), "cid": str(client_id)},
    )
    memo = result.scalar_one_or_none()
    if not memo:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Memo not found")
    if memo != "approved":
        raise HTTPException(
            status.HTTP_400_BAD_REQUEST,
            f"Memo must be approved before publishing (current status: {memo})",
        )

    await db.execute(
        text("""
            UPDATE memos
            SET status = 'published', published_at = now()
            WHERE id = :mid AND client_id = :cid
        """),
        {"mid": str(memo_id), "cid": str(client_id)},
    )
    await db.commit()

    return {"status": "published", "memo_id": str(memo_id)}


@router.get("/{memo_id}/export", response_class=PlainTextResponse)
async def export_memo_markdown(
    client_id: UUID,
    memo_id: UUID,
    user: AuthUser = Depends(require_roles(*OPS_ROLES)),
    db: AsyncSession = Depends(get_db),
) -> PlainTextResponse:
    """Export a memo as raw Markdown text."""
    await has_client_access(client_id, user, db)

    result = await db.execute(
        text("SELECT COALESCE(final_md, draft_md) FROM memos WHERE id = :mid AND client_id = :cid"),
        {"mid": str(memo_id), "cid": str(client_id)},
    )
    md = result.scalar_one_or_none()
    if not md:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Memo not found")

    return PlainTextResponse(content=md, media_type="text/markdown")
